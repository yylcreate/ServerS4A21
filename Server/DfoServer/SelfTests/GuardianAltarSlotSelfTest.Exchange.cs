        private static void VerifyExchangeWire(Action<string, bool> check)
        {
            // Independent captured unit request, not bytes generated by the parser.
            var captured = Convert.FromHexString("000000000000000000000000000001000000000100000003A00F00000100000000E8030000");
            var unit = new GuardianAltarExchangeRequest(1,
                new GuardianAltarExchangeEndpoint(1, 3, 4000), new GuardianAltarExchangeEndpoint(1, 0, 1000));
            check("captured 37B EXCHANGE request has two packed unit endpoints and a separate zero byte",
                GuardianAltarExchangeRequestParser.TryParse(captured, out var parsed) && parsed == unit
                && ExchangeBody(unit).SequenceEqual(captured));
            check("exchange success 27B ACK contains original resources for the client's opposite-slot writes",
                GuardianAltarExchangeAckBodyBuilder.Build(unit,
                    new GuardianAltarSlot(0, 1, 3, 1000), new GuardianAltarSlot(0, 1, 0, 4000))
                .SequenceEqual(Convert.FromHexString("0100000000010000000100000003A00F00000100000000E8030000")));
            var skill = new GuardianAltarExchangeRequest(1,
                new GuardianAltarExchangeEndpoint(2, 1, 1501), new GuardianAltarExchangeEndpoint(2, 2, 0));
            var skillBody = Convert.FromHexString("000000000000000000000000000001000000000200000001DD050000020000000200000000");
            check("same packed exchange contract supports a skill moving into an empty slot",
                GuardianAltarExchangeRequestParser.TryParse(skillBody, out var parsedSkill) && parsedSkill == skill
                && GuardianAltarExchangeAckBodyBuilder.Build(skill,
                    new GuardianAltarSlot(0, 2, 1, 0), new GuardianAltarSlot(0, 2, 2, 1501))
                .SequenceEqual(Convert.FromHexString("0100000000010000000200000001DD050000020000000200000000")));
            check("exchange outer rejection has no dedicated 26B payload",
                GuardianAltarExchangeAckBodyBuilder.BuildRejected().SequenceEqual(new byte[] { 0, 4 }));
            foreach (var invalid in new byte[][] { null, captured[..36], captured.Concat(new byte[1]).ToArray(),
                Mutate(captured, 0, 1), Mutate(captured, 13, 1), Mutate(captured, 18, 1),
                Mutate(captured, 14, 0, 0, 0, 0), Mutate(captured, 19, 0, 0, 0, 0),
                Mutate(captured, 28, 2, 0, 0, 0), Mutate(captured, 23, 6), Mutate(captured, 32, 6),
                Mutate(captured, 32, 3), Mutate(captured, 24, 255, 255, 255, 255),
                Mutate(captured, 33, 255, 255, 255, 255),
                Mutate(Mutate(captured, 24, 0, 0, 0, 0), 33, 0, 0, 0, 0) })
                check("exchange parser rejects malformed or cross-type/same-index/noop endpoints",
                    !GuardianAltarExchangeRequestParser.TryParse(invalid, out _));
            check("exchange ACK cannot echo post-state values as if they were the original request",
                Throws<ArgumentException>(() => GuardianAltarExchangeAckBodyBuilder.Build(unit,
                    new GuardianAltarSlot(0, 1, 3, 4000), new GuardianAltarSlot(0, 1, 0, 1000)))
                && Throws<ArgumentException>(() => GuardianAltarExchangeAckBodyBuilder.Build(unit,
                    new GuardianAltarSlot(1, 1, 3, 1000), new GuardianAltarSlot(0, 1, 0, 4000))));
        }

        private static void VerifyExchangeDomain(GameDatabase database, GuardianAltarProgressService service,
            GuardianAltarMenuDefinition definition, string path, Action<string, bool> check)
        {
            for (var id = 8; id <= 11; id++)
            {
                Sql(database, $"INSERT INTO characters(character_id,account_id,name,level) VALUES({id},1,'guardian-exchange-{id}',70);");
                service.LoadMenu(id, Anchor);
                Sql(database, $"UPDATE character_guardian_altar SET stage_stars=100,available_stars=100 WHERE character_id={id};");
                service.Buy(id, 1, new GuardianAltarPurchaseRequest(1, 0, LearnedUnit, 1));
                service.Buy(id, 1, new GuardianAltarPurchaseRequest(1, 1, ActiveSkill, 1));
                service.SetSlot(id, 1, new GuardianAltarSlotRequest(1, true, 1, 5, LearnedUnit));
                service.SetSlot(id, 1, new GuardianAltarSlotRequest(1, true, 2, 2, ActiveSkill));
            }
            var before = service.LoadMenu(8, Anchor);
            var unit = Exchange(before, 1, 0, 5);
            var exchanged = service.ExchangeSlots(8, 1, unit);
            check("two occupied unit slots exchange together without changing balances or any other progress",
                ExchangeMatches(exchanged, unit) && exchanged.Changed && SameExceptEndpoints(before, exchanged.Progress, unit));
            check("exchange leaves previously captured menu snapshots immutable",
                Slot(before, 1, 0).ResourceId == unit.First.ResourceId && Slot(before, 1, 5).ResourceId == unit.Second.ResourceId);
            Sql(database, "CREATE TRIGGER forbid_exchange_replay BEFORE UPDATE OF resource_id ON character_guardian_altar_slots "
                + "WHEN NEW.character_id=8 BEGIN SELECT RAISE(ABORT,'exchange replay must not write'); END;");
            try
            {
                var replay = service.ExchangeSlots(8, 1, unit);
                check("an exact post-state retry never swaps resources back or rewrites either slot",
                    ExchangeMatches(replay, unit) && !replay.Changed && Same(exchanged.Progress, replay.Progress));
            }
            finally { Sql(database, "DROP TRIGGER forbid_exchange_replay;"); }
            var inverse = Exchange(exchanged.Progress, 1, 0, 5);
            var reversed = service.ExchangeSlots(8, 1, inverse);
            check("a new inverse intent declares current resources and can reverse the exchange",
                reversed.Accepted && reversed.Changed && Same(before, reversed.Progress));
            var skill = Exchange(before, 2, 0, 2);
            var skillSwap = service.ExchangeSlots(8, 1, skill);
            check("skill exchanges use the same transaction owner and preserve all unit slots",
                ExchangeMatches(skillSwap, skill) && skillSwap.Changed
                && SameExceptEndpoints(before, skillSwap.Progress, skill));
            var move = Exchange(skillSwap.Progress, 2, 0, 3);
            var moved = service.ExchangeSlots(8, 1, move);
            check("moving a learned resource into an authoritative empty unlocked slot atomically empties its origin",
                ExchangeMatches(moved, move) && moved.Changed && moved.First.ResourceId == 0
                && moved.Second.ResourceId == move.First.ResourceId && SameExceptEndpoints(skillSwap.Progress, moved.Progress, move));
            var stale = service.ExchangeSlots(8, 1, skill);
            check("a late request whose endpoints match neither pre-state nor post-state cannot alter subsequent movement",
                !stale.Accepted && !stale.Changed && Same(moved.Progress, stale.Progress));
            foreach (var invalid in new[] {
                move with { RidableId = 2 },
                move with { First = move.First with { SlotType = 0 } },
                move with { First = move.First with { SlotType = 3 } },
                move with { Second = move.Second with { SlotType = 1 } },
                move with { Second = move.Second with { SlotIndex = 6 } },
                move with { Second = move.Second with { SlotIndex = 0 } },
                move with { Second = move.Second with { SlotIndex = 4 } },
                move with { Second = move.Second with { ResourceId = -1 } },
                move with { First = move.First with { ResourceId = 100010 } }, // passive
                move with { First = move.First with { ResourceId = 100013 } }, // not unlocked
                move with { First = move.First with { ResourceId = 100015 } }, // not learned
                move with { First = move.First with { ResourceId = LearnedUnit } }, // wrong type
                move with { First = move.First with { ResourceId = 999999 } },
                new GuardianAltarExchangeRequest(1, new GuardianAltarExchangeEndpoint(2, 0, 0),
                    new GuardianAltarExchangeEndpoint(2, 1, 0)),
            })
            {
                var rejected = service.ExchangeSlots(8, 1, invalid);
                check("invalid, locked, passive, unlearned or mismatched exchange fails without mutation",
                    !rejected.Accepted && !rejected.Changed && Same(moved.Progress, rejected.Progress));
            }
            check("exchange account ownership rejects access to another role",
                Throws<InvalidOperationException>(() => service.ExchangeSlots(8, 2, move)) && Same(moved.Progress, service.LoadMenu(8, Anchor)));
            var persisted = new GuardianAltarProgressService(new GameDatabase(path, ServerPaths.SchemaFilePath),
                new DailyResetService(database), definition).LoadMenu(8, Anchor);
            check("a recreated progress owner reads both persisted exchange endpoints", Same(moved.Progress, persisted));
            var nextDay = service.LoadMenu(8, Anchor.AddDays(1));
            check("daily ticket refill leaves exchanged slot configuration intact", moved.Progress.Slots.SequenceEqual(nextDay.Slots));

            var rollbackBefore = service.LoadMenu(9, Anchor);
            var rollbackRequest = Exchange(rollbackBefore, 1, 0, 5);
            check("obsolete identity rejects exchange before either endpoint changes",
                Throws<InvalidOperationException>(() => service.ExchangeSlots(9, 1, rollbackRequest, () => false))
                && Same(rollbackBefore, service.LoadMenu(9, Anchor)));
            var calls = 0;
            check("identity loss at final exchange commit fence rolls back both endpoint writes",
                Throws<InvalidOperationException>(() => service.ExchangeSlots(9, 1, rollbackRequest, () => ++calls == 1))
                && calls == 2 && Same(rollbackBefore, service.LoadMenu(9, Anchor)));
            Sql(database, "CREATE TRIGGER reject_second_exchange_endpoint AFTER UPDATE OF resource_id ON character_guardian_altar_slots "
                + "WHEN NEW.character_id=9 AND NEW.slot_type=1 AND NEW.slot_index=5 "
                + "BEGIN SELECT RAISE(ABORT,'reject exchange second endpoint'); END;");
            try
            {
                check("second endpoint database failure rolls back the first endpoint as well",
                    Throws<SqliteException>(() => service.ExchangeSlots(9, 1, rollbackRequest))
                    && Same(rollbackBefore, service.LoadMenu(9, Anchor)));
            }
            finally { Sql(database, "DROP TRIGGER reject_second_exchange_endpoint;"); }
            var concurrentBefore = service.LoadMenu(10, Anchor);
            var concurrentRequest = Exchange(concurrentBefore, 1, 0, 5);
            var concurrent = Task.WhenAll(Enumerable.Range(0, 3).Select(_ => Task.Run(() =>
                service.ExchangeSlots(10, 1, concurrentRequest)))).GetAwaiter().GetResult();
            check("concurrent identical exchange requests commit one swap and all project the same final state",
                concurrent.All(x => ExchangeMatches(x, concurrentRequest)) && concurrent.Count(x => x.Changed) == 1
                && concurrent.All(x => Same(x.Progress, service.LoadMenu(10, Anchor))));
            var conflictBefore = service.LoadMenu(11, Anchor);
            var conflictA = Exchange(conflictBefore, 1, 0, 5);
            var conflictB = Exchange(conflictBefore, 1, 0, 4);
            var conflicts = Task.WhenAll(new[] { conflictA, conflictB }.Select(r => Task.Run(() =>
                service.ExchangeSlots(11, 1, r)))).GetAwaiter().GetResult();
            check("concurrent conflicting exchanges preserve a complete slot vector and accept only one current pre-state",
                conflicts.Count(x => x.Accepted && x.Changed) == 1 && conflicts.Count(x => !x.Accepted) == 1
                && service.LoadMenu(11, Anchor).Slots.Count(x => x.SlotType == 1 && x.ResourceId > 0) == conflictBefore.Slots.Count(x => x.SlotType == 1 && x.ResourceId > 0));
        }

        private static async Task VerifyExchangeRequests(GameDatabase database, GuardianAltarProgressService progress,
            Action<string, bool> check)
        {
            using var fixture = new SlotRequestFixture(progress);
            var before = progress.LoadMenu(3, Anchor);
            var request = Exchange(before, 2, 0, 2);
            await fixture.DispatchExchange(request);
            check("closed exchange rejects without entering the progress owner",
                IsExchangeFailure(fixture.Packets.Single()) && fixture.Probe.Calls == 0 && Same(before, progress.LoadMenu(3, Anchor)));
            fixture.Open();
            fixture.Packets.Clear();
            await fixture.DispatchExchange(request, ExchangeBody(request)[..36]);
            check("malformed exchange is rejected before its durable owner is invoked",
                IsExchangeFailure(fixture.Packets.Single()) && fixture.Probe.Calls == 0 && Same(before, progress.LoadMenu(3, Anchor)));
            foreach (var restriction in new[] { "trade", "mercenary", "level", "presence", "combat" })
            {
                fixture.Packets.Clear();
                fixture.Trading = restriction == "trade";
                fixture.Mercenary.Assigned = restriction == "mercenary";
                fixture.Session.Player.Level = (byte)(restriction == "level" ? 49 : 70);
                fixture.Session.Player.TownPresenceReady = restriction != "presence";
                fixture.Session.Player.UserState = (byte)(restriction == "combat" ? 1 : 0);
                await fixture.DispatchExchange(request);
                check("exchange entry restrictions remain enforced: " + restriction,
                    fixture.Packets.Count == 1 && IsExchangeFailure(fixture.Packets[0])
                    && fixture.Probe.Calls == 0 && Same(before, progress.LoadMenu(3, Anchor)));
            }
            fixture.Trading = false;
            fixture.Mercenary.Assigned = false;
            fixture.Session.Player.Level = 70;
            fixture.Session.Player.TownPresenceReady = true;
            fixture.Session.Player.UserState = 0;
            foreach (var fence in new[] { "account-reference", "game-session", "directory", "selection", "run", "revision" })
            {
                fixture.Packets.Clear();
                fixture.Probe.DuringFence = call =>
                {
                    if (call != 2) return;
                    switch (fence)
                    {
                        case "account-reference": fixture.Session.Account = new AccountRecord { AccountId = 1 }; break;
                        case "game-session": fixture.Session.GameSession = GameSessionIdentity(); break;
                        case "directory": fixture.ReplaceSession(); break;
                        case "selection": fixture.Session.Player.BeginDungeonSelection(ExchangeAnchor(fixture.Session)); break;
                        case "run": fixture.Session.Player.NextDungeonRunGeneration(); break;
                        case "revision": fixture.Open(); break;
                    }
                };
                await fixture.DispatchExchange(request);
                check("exchange final commit rechecks original identity and generation: " + fence,
                    Same(before, progress.LoadMenu(3, Anchor))
                    && (fence == "revision" ? fixture.Packets.Count == 2 && IsExchangeFailure(fixture.Packets[0])
                        : fixture.Packets.Count == 0));
                fixture.Probe.DuringFence = null;
                fixture.ReplaceSession();
            }
            fixture.Packets.Clear();
            fixture.FailNextWrite = true;
            await fixture.DispatchExchange(request);
            var committed = progress.LoadMenu(3, Anchor);
            check("exchange persists both endpoints when the success ACK is lost",
                fixture.Packets.Count == 0 && Slot(committed, 2, 0).ResourceId == request.Second.ResourceId
                && Slot(committed, 2, 2).ResourceId == request.First.ResourceId && SameExceptEndpoints(before, committed, request));
            await fixture.DispatchExchange(request);
            check("lost ACK retry projects the same pre-state 27B payload without reversing durable slots",
                IsExchangeSuccess(fixture.Packets.Single(), request, committed) && Same(committed, progress.LoadMenu(3, Anchor)));
            var inverse = Exchange(committed, 2, 0, 2);
            fixture.Packets.Clear();
            fixture.BeforePrepare = () => fixture.Session.Account = new AccountRecord { AccountId = 1 };
            await fixture.DispatchExchange(inverse);
            check("account reference replacement in send prepare suppresses an old ACK without undoing its commit",
                fixture.Packets.Count == 0 && Same(before, progress.LoadMenu(3, Anchor)));
            fixture.ReplaceSession();
            fixture.Packets.Clear();
            fixture.BeforePrepare = () => fixture.Session.Player.BeginDungeonSelection(ExchangeAnchor(fixture.Session));
            await fixture.DispatchExchange(request);
            var epochCommitted = progress.LoadMenu(3, Anchor);
            check("selection generation change in send prepare suppresses the exchange ACK for a later selection",
                fixture.Packets.Count == 0 && Same(committed, epochCommitted));
            fixture.ReplaceSession();
            fixture.Packets.Clear();
            var noticeRequest = Exchange(epochCommitted, 2, 0, 2);
            Sql(database, "CREATE TRIGGER reject_exchange_for_notice AFTER UPDATE OF resource_id ON character_guardian_altar_slots "
                + "WHEN NEW.character_id=3 AND NEW.slot_type=2 AND NEW.slot_index=2 "
                + "BEGIN SELECT RAISE(ABORT,'exchange notice source test'); END;");
            try
            {
                fixture.AfterWrite = () => fixture.Session.Account = new AccountRecord { AccountId = 1 };
                await fixture.DispatchExchange(noticeRequest);
                check("replacement during the rejection ACK write suppresses its separately prepared optional notice",
                    fixture.Packets.Count == 1 && IsExchangeFailure(fixture.Packets[0])
                    && Same(epochCommitted, progress.LoadMenu(3, Anchor)));
                fixture.ReplaceSession();
                fixture.Packets.Clear();
                await fixture.DispatchExchange(noticeRequest);
                check("a current rejected source receives its ACK then an independently prepared notice",
                    fixture.Packets.Count == 2 && IsExchangeFailure(fixture.Packets[0]) && Notice(fixture.Packets[1])
                    && Same(epochCommitted, progress.LoadMenu(3, Anchor)));
            }
            finally { Sql(database, "DROP TRIGGER reject_exchange_for_notice;"); }
        }

        private static void VerifyRealExchangePlan(GameDatabase database, Action<string, bool> check)
        {
            var definition = GuardianAltarMenuDefinition.Load();
            Sql(database, "INSERT INTO characters(character_id,account_id,name,level) VALUES(12,1,'guardian-real-exchange',70);");
            var service = new GuardianAltarProgressService(database, new DailyResetService(database), definition);
            var before = service.LoadMenu(12, Anchor);
            var source = before.Slots.First(x => x.SlotType == 1 && x.Locked == 0 && x.ResourceId > 0);
            var target = before.Slots.First(x => x.SlotType == 1 && x.Locked == 0 && x.ResourceId == 0);
            var request = Exchange(before, 1, source.SlotIndex, target.SlotIndex);
            var oldPlan = definition.CreateStartPlan(definition.FirstDungeonId, 0, before);
            var oldMenu = GuardianAltarMenuBodyBuilder.Build(oldPlan.Progress);
            var result = service.ExchangeSlots(12, 1, request);
            var newPlan = definition.CreateStartPlan(definition.FirstDungeonId, 0, result.Progress);
            var expected = oldPlan.Units.Select(x => x.Slot == source.SlotIndex
                ? x with { Slot = target.SlotIndex } : x).OrderBy(x => x.Slot).ToArray();
            check("current PVF exchange maps learned resource levels into the next run's actual summon slot",
                ExchangeMatches(result, request) && result.Changed && newPlan.Units.SequenceEqual(expected));
            check("current PVF exchange never edits an already frozen run's progress or units",
                oldMenu.SequenceEqual(GuardianAltarMenuBodyBuilder.Build(oldPlan.Progress))
                && oldPlan.Units.Any(x => x.Slot == source.SlotIndex)
                && Slot(oldPlan.Progress, 1, target.SlotIndex).ResourceId == 0);
        }

        private static GuardianAltarExchangeRequest Exchange(GuardianAltarProgressSnapshot snapshot, int type, byte a, byte b)
            => new(snapshot.Header.RidableId, new GuardianAltarExchangeEndpoint(type, a, Slot(snapshot, type, a).ResourceId),
                new GuardianAltarExchangeEndpoint(type, b, Slot(snapshot, type, b).ResourceId));
        private static DungeonTownReturnAnchor ExchangeAnchor(EnhancedClientSession session)
            => new(session.Player.CurTownId, session.Player.CurAreaId, session.Player.CurPosX,
                session.Player.CurPosY, session.Player.CurDirection, session.Player.CurAreaState);
        private static bool ExchangeMatches(GuardianAltarExchangeResult result, GuardianAltarExchangeRequest request)
            => result.Accepted && result.First == new GuardianAltarSlot(0, request.First.SlotType, request.First.SlotIndex, request.Second.ResourceId)
                && result.Second == new GuardianAltarSlot(0, request.Second.SlotType, request.Second.SlotIndex, request.First.ResourceId)
                && result.Progress.Slots.Contains(result.First) && result.Progress.Slots.Contains(result.Second);
        private static bool SameExceptEndpoints(GuardianAltarProgressSnapshot left, GuardianAltarProgressSnapshot right,
            GuardianAltarExchangeRequest request)
        {
            bool Other(GuardianAltarSlot slot) => !(slot.SlotType == request.First.SlotType
                && (slot.SlotIndex == request.First.SlotIndex || slot.SlotIndex == request.Second.SlotIndex));
            return left.CharacterId == right.CharacterId && left.Header == right.Header
                && left.Stages.SequenceEqual(right.Stages) && left.Purchases.SequenceEqual(right.Purchases)
                && left.Achievements.SequenceEqual(right.Achievements)
                && left.Slots.Where(Other).SequenceEqual(right.Slots.Where(Other));
        }
        private static byte[] ExchangeBody(GuardianAltarExchangeRequest request)
        {
            var body = new byte[37];
            BinaryPrimitives.WriteInt32LittleEndian(body.AsSpan(14), request.RidableId);
            BinaryPrimitives.WriteInt32LittleEndian(body.AsSpan(19), request.First.SlotType);
            body[23] = request.First.SlotIndex;
            BinaryPrimitives.WriteInt32LittleEndian(body.AsSpan(24), request.First.ResourceId);
            BinaryPrimitives.WriteInt32LittleEndian(body.AsSpan(28), request.Second.SlotType);
            body[32] = request.Second.SlotIndex;
            BinaryPrimitives.WriteInt32LittleEndian(body.AsSpan(33), request.Second.ResourceId);
            return body;
        }
        private static bool IsExchangeSuccess(byte[] packet, GuardianAltarExchangeRequest request, GuardianAltarProgressSnapshot snapshot)
            => packet.Length == 42 && packet[0] == 1
                && BitConverter.ToUInt16(packet, 1) == (ushort)CmdPacketTypeA21.ADVANCE_ALTAR_EXCHANGE_SLOT
                && BitConverter.ToUInt32(packet, 3) == packet.Length
                && packet.AsSpan(15).SequenceEqual(GuardianAltarExchangeAckBodyBuilder.Build(request,
                    Slot(snapshot, request.First.SlotType, request.First.SlotIndex),
                    Slot(snapshot, request.Second.SlotType, request.Second.SlotIndex)));
        private static bool IsExchangeFailure(byte[] packet)
            => packet.Length == 17 && packet[0] == 1
                && BitConverter.ToUInt16(packet, 1) == (ushort)CmdPacketTypeA21.ADVANCE_ALTAR_EXCHANGE_SLOT
                && packet[15] == 0 && packet[16] == 4;
    }
